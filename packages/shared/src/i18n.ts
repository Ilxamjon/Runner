export const translations: Record<AppLocale, TranslationTree> = { uz, ru };

function getNestedValue(tree: TranslationTree, key: string): string | undefined {
  const parts = key.split('.');
  let current: string | TranslationTree | undefined = tree;
  for (const part of parts) {
    if (typeof current !== 'object' || current === null) return undefined;
    current = current[part];
  }
  return typeof current === 'string' ? current : undefined;
}

export function t(locale: AppLocale, key: string): string {
  return getNestedValue(translations[locale], key) ?? key;
}
